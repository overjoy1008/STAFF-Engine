using System;
using UnityEngine;
#if ENABLE_INPUT_SYSTEM
using UnityEngine.InputSystem;
#endif
namespace Staff.Nishita
{
 [ExecuteAlways]
 public sealed class NishitaComparison : MonoBehaviour
 {
  [Serializable] public class Variant { public Material sky; [ColorUsage(false,true)] public Color ambientSky,ambientHorizon; }
  [Serializable] public class Preset { public string label; public float elevation,exposure; public Variant single,multiple; public Color sunColor=Color.white;public float sunIntensity; }
  public enum DisplayMode { Compare, Single, Multiple }
  public Preset[] presets;
  public NishitaAtmosphere atmosphere;
  public Texture2D numberAtlas;
  public bool showParameters=true;
  public Texture2D agxLut;
  public Camera singleCamera,multipleCamera;
  public Light sun;
  public GameObject gallery;
  public DisplayMode displayMode=DisplayMode.Compare;
  [Range(0,2)] public int presetIndex=1;
  [Range(-12,12)] public float exposure=-2;
  public bool showGallery=true;
  [Range(25,90)] public float fieldOfView=58;
  public float yaw=64,pitch=-9;
  public Preset Current => presets[Mathf.Clamp(presetIndex,0,presets.Length-1)];
  GUIStyle heading,small,label,button;
  Vector2 parameterScroll;
  void OnEnable(){ApplyLayout();}
  void Update(){
   if(Application.isPlaying){
    Vector2 delta=Vector2.zero; float scroll=0;bool drag=false;
#if ENABLE_INPUT_SYSTEM
    if(Mouse.current!=null){drag=Mouse.current.rightButton.isPressed;delta=Mouse.current.delta.ReadValue();scroll=Mouse.current.scroll.ReadValue().y/120;}
#else
    drag=Input.GetMouseButton(1);delta=new Vector2(Input.GetAxis("Mouse X")*12,Input.GetAxis("Mouse Y")*12);scroll=Input.mouseScrollDelta.y;
#endif
    if(drag){yaw+=delta.x*0.13f;pitch=Mathf.Clamp(pitch-delta.y*0.13f,-75,65);}
    fieldOfView=Mathf.Clamp(fieldOfView-scroll*2,25,90);
   }
   ApplyLayout();
  }
  public void SelectPreset(int index){presetIndex=Mathf.Clamp(index,0,presets.Length-1);exposure=Current.exposure;
   if(atmosphere){atmosphere.useDayCycle=true;atmosphere.timeOfDay=new[]{12f,17.5f,18.5f}[presetIndex];atmosphere.animate=false;atmosphere.Tick(true);}ApplyLayout();}
  public void ApplyLayout(){
   if(!singleCamera||!multipleCamera)return;
   bool compare=displayMode==DisplayMode.Compare;
   singleCamera.enabled=displayMode!=DisplayMode.Multiple;
   multipleCamera.enabled=displayMode!=DisplayMode.Single;
   singleCamera.rect=compare?new Rect(0,0,.5f,1):new Rect(0,0,1,1);
   multipleCamera.rect=compare?new Rect(.5f,0,.5f,1):new Rect(0,0,1,1);
   foreach(var cam in new[]{singleCamera,multipleCamera}){cam.fieldOfView=fieldOfView;cam.transform.rotation=Quaternion.Euler(pitch,yaw,0);}
   if(gallery && gallery.activeSelf!=showGallery)gallery.SetActive(showGallery);
  }
  // All rendered numerical glyphs come from the actual LaTeX atlas generated by Tools/MathTypography.
  void Number(Rect rect,string value,float size=15){
   if(!numberAtlas)return;
   const string characters="0123456789-.:";
   float cw=size*.65f,x=rect.xMax-value.Length*cw;
   foreach(char ch in value){int index=characters.IndexOf(ch);if(index>=0)GUI.DrawTextureWithTexCoords(new Rect(x,rect.y,cw,size),numberAtlas,new Rect(index/13f,0,1/13f,1));x+=cw;}
  }
  float Slider(string title,float value,float min,float max,bool logarithmic=false,string format="0.00"){
   GUILayout.BeginHorizontal();GUILayout.Label(title,small,GUILayout.Width(130));
   float mapped=logarithmic?Mathf.Log10(1+value):value;float originalValue=mapped;
   mapped=GUILayout.HorizontalSlider(mapped,logarithmic?Mathf.Log10(1+min):min,logarithmic?Mathf.Log10(1+max):max,GUILayout.Width(102));
   float result=Mathf.Abs(mapped-originalValue)<1e-6f?value:(logarithmic?Mathf.Pow(10,mapped)-1:mapped);
   Rect r=GUILayoutUtility.GetRect(64,20,GUILayout.Width(64));Number(r,result.ToString(format,System.Globalization.CultureInfo.InvariantCulture));GUILayout.EndHorizontal();return result;
  }
  void OnGUI(){
   if(presets==null||presets.Length==0)return;
   if(heading==null){heading=new GUIStyle(GUI.skin.label){fontSize=22,fontStyle=FontStyle.Bold};heading.normal.textColor=Color.white;
    small=new GUIStyle(GUI.skin.label){fontSize=12};small.normal.textColor=new Color(.8f,.84f,.9f);
    label=new GUIStyle(heading){fontSize=16};button=new GUIStyle(GUI.skin.button){fontSize=13,fixedHeight=28};}
   float scale=Mathf.Min(1,Screen.width/1080f);var old=GUI.matrix;GUI.matrix=Matrix4x4.Scale(new Vector3(scale,scale,1));
   float width=Screen.width/scale,height=Screen.height/scale;var original=GUI.color;
   GUI.color=new Color(.035f,.045f,.065f,.94f);GUI.DrawTexture(new Rect(0,0,width,168),Texture2D.whiteTexture);GUI.color=original;
   GUI.Label(new Rect(24,10,450,31),"NISHITA  /  LIVING ATMOSPHERE",heading);
   GUI.Label(new Rect(24,44,900,22),atmosphere?atmosphere.Status+"  /  Blender spectral models  /  AgX":"Blender reference skies",small);
   GUILayout.BeginArea(new Rect(24,74,width-48,88));GUILayout.BeginHorizontal();
   foreach(DisplayMode mode in Enum.GetValues(typeof(DisplayMode))){GUI.backgroundColor=mode==displayMode?new Color(.42f,.72f,.88f):Color.white;if(GUILayout.Button(mode.ToString(),button,GUILayout.Width(91)))displayMode=mode;}
   GUI.backgroundColor=Color.white;GUILayout.Space(12);
   for(int i=0;i<presets.Length;i++)if(GUILayout.Button(presets[i].label,button,GUILayout.Width(102)))SelectPreset(i);
   showGallery=GUILayout.Toggle(showGallery," Material gallery",GUILayout.Width(132));
   if(GUILayout.Button(showParameters?"Hide controls":"Parameters",button,GUILayout.Width(116)))showParameters=!showParameters;
   if(GUILayout.Button("Face sun",button,GUILayout.Width(92))&&atmosphere){yaw=atmosphere.Rotation-8;pitch=-Mathf.Clamp(atmosphere.Elevation,5,55);}
   GUILayout.EndHorizontal();GUILayout.Space(9);GUILayout.BeginHorizontal();
   if(atmosphere){
    atmosphere.useDayCycle=GUILayout.Toggle(atmosphere.useDayCycle," Solar day",GUILayout.Width(95));
    GUI.enabled=atmosphere.useDayCycle;
    if(GUILayout.Button(atmosphere.animate?"Pause":"Play",GUILayout.Width(64)))atmosphere.animate=!atmosphere.animate;
    GUILayout.Label("Midnight",small,GUILayout.Width(55));float hour=GUILayout.HorizontalSlider(atmosphere.timeOfDay,0,24,GUILayout.Width(350));GUILayout.Label("Midnight",small,GUILayout.Width(55));
    if(Mathf.Abs(hour-atmosphere.timeOfDay)>.0001f){atmosphere.timeOfDay=hour;atmosphere.animate=false;}
    int minutes=Mathf.FloorToInt(Mathf.Repeat(atmosphere.timeOfDay,24)*60);Rect time=GUILayoutUtility.GetRect(72,23,GUILayout.Width(72));Number(time,(minutes/60).ToString("00")+":"+(minutes%60).ToString("00"),20);
    GUI.enabled=true;GUILayout.Label("local solar time",small,GUILayout.Width(100));
   }
   GUILayout.EndHorizontal();GUILayout.EndArea();
   if(atmosphere&&showParameters){
    float x=width-354;float ph=Mathf.Min(height-290,540);
    GUI.color=new Color(.035f,.045f,.065f,.94f);GUI.DrawTexture(new Rect(x-10,182,344,ph),Texture2D.whiteTexture);GUI.color=original;
    GUILayout.BeginArea(new Rect(x,191,325,ph-18));parameterScroll=GUILayout.BeginScrollView(parameterScroll,false,true);
    GUI.Label(new Rect(0,0,320,24),"ATMOSPHERE & SUN",label);GUILayout.Space(29);
    atmosphere.airDensity=Slider("Air density",atmosphere.airDensity,0,1000,true);
    atmosphere.aerosolDensity=Slider("Aerosol density",atmosphere.aerosolDensity,0,1000,true);
    atmosphere.ozoneDensity=Slider("Ozone density",atmosphere.ozoneDensity,0,1000,true);
    atmosphere.altitude=Slider("Altitude / meters",atmosphere.altitude,0,100000,true,"0");
    GUILayout.Space(5);atmosphere.sunDisc=GUILayout.Toggle(atmosphere.sunDisc," Show solar disc");
    atmosphere.sunRadius=Slider("Sun radius / degrees",atmosphere.sunRadius,0,45,true,"0.000");
    atmosphere.sunIntensity=Slider("Sun disc intensity",atmosphere.sunIntensity,0,100,true);
    atmosphere.brightness=Slider("World brightness",atmosphere.brightness,0,100,true);
    exposure=Slider("Exposure / stops",exposure,-12,12,false);
    GUILayout.Space(5);
    GUI.enabled=!atmosphere.useDayCycle;
    float elevation=Slider("Sun elevation",atmosphere.useDayCycle?atmosphere.Elevation:atmosphere.sunElevation,-90,90,false,"0.0");
    float rotation=Slider("Sun rotation",atmosphere.useDayCycle?atmosphere.Rotation:atmosphere.sunRotation,0,360,false,"0.0");
    if(!atmosphere.useDayCycle){atmosphere.sunElevation=elevation;atmosphere.sunRotation=rotation;}GUI.enabled=true;
    GUILayout.Label(atmosphere.useDayCycle?"Solar path controls elevation and rotation":"Manual solar position",small);
    GUILayout.Space(5);GUI.enabled=atmosphere.useDayCycle;
    atmosphere.latitude=Slider("Latitude",atmosphere.latitude,-89,89,false,"0.0");
    atmosphere.solarDeclination=Slider("Season / declination",atmosphere.solarDeclination,-23.44f,23.44f,false,"0.00");
    atmosphere.northRotation=Slider("North rotation",atmosphere.northRotation,0,360,false,"0.0");
    atmosphere.dayDurationSeconds=Slider("Day duration / sec",atmosphere.dayDurationSeconds,10,1800,true,"0");GUI.enabled=true;
    GUILayout.Space(7);if(GUILayout.Button("Reset atmosphere")){atmosphere.airDensity=atmosphere.aerosolDensity=atmosphere.ozoneDensity=1;atmosphere.altitude=0;atmosphere.sunRadius=.2725f;atmosphere.sunIntensity=atmosphere.brightness=1;atmosphere.sunDisc=true;exposure=-2;}
    GUILayout.Label("Sun Size in Blender is the diameter.",small);GUILayout.EndScrollView();GUILayout.EndArea();
   }
   if(displayMode==DisplayMode.Compare){GUI.color=new Color(.8f,.85f,.9f,.4f);GUI.DrawTexture(new Rect(width/2-1,168,2,height-168),Texture2D.whiteTexture);GUI.color=original;}
   float panel=displayMode==DisplayMode.Compare?width/2:width;
   for(int i=0;i<(displayMode==DisplayMode.Compare?2:1);i++){
    bool multi=displayMode==DisplayMode.Multiple||(displayMode==DisplayMode.Compare&&i==1);float x=i*panel+24;
    GUI.color=new Color(.035f,.045f,.065f,.9f);GUI.DrawTexture(new Rect(x-10,height-91,panel-28,49),Texture2D.whiteTexture);GUI.color=original;
    GUI.Label(new Rect(x,height-87,panel-40,23),multi?"MULTIPLE SCATTERING":"SINGLE SCATTERING",label);
    GUI.Label(new Rect(x,height-65,panel-40,20),multi?"Spectral multiple-scattering atmosphere":"Classic spectral Nishita atmosphere",small);
   }
   GUI.Label(new Rect(24,height-29,width-40,22),"Sun-only atmosphere  /  shared exposure  /  right-drag to look, scroll to zoom  /  gallery lighting approximated",small);
   GUI.matrix=old;ApplyLayout();
  }
 }
}
